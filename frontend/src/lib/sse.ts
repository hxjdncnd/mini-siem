export interface SseFrame {
  event: string;
  data: string;
}

/**
 * Pulls complete server-sent-event frames out of streamed text. Returns the frames found and whatever
 * trailing text is still an unfinished frame, to be joined with the next chunk. Comment lines
 * (": keepalive") and frames with no data are dropped.
 */
export function parseSse(buffer: string): { frames: SseFrame[]; rest: string } {
  const text = buffer.replace(/\r\n?/g, "\n");
  const blocks = text.split("\n\n");
  const rest = blocks.pop() ?? "";
  const frames: SseFrame[] = [];
  for (const block of blocks) {
    let event = "message";
    const data: string[] = [];
    for (const line of block.split("\n")) {
      if (line === "" || line.startsWith(":")) continue;
      const colon = line.indexOf(":");
      const field = colon === -1 ? line : line.slice(0, colon);
      const value = colon === -1 ? "" : line.slice(colon + 1).replace(/^ /, "");
      if (field === "event") event = value;
      else if (field === "data") data.push(value);
    }
    if (data.length > 0) frames.push({ event, data: data.join("\n") });
  }
  return { frames, rest };
}
